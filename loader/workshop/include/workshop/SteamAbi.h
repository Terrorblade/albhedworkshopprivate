	// CCallbackBase, for SteamAPI_RegisterCallback.
	//
	// Provenance: [S1] steamworks_sdk_131/steam_api.h, class CCallbackBase at line 162,
	// which in full is:
	//
	//     class CCallbackBase
	//     {
	//     public:
	//         CCallbackBase() { m_nCallbackFlags = 0; m_iCallback = 0; }
	//         // don't add a virtual destructor because we export this binary interface across dll's
	//         virtual void Run( void *pvParam ) = 0;
	//         virtual void Run( void *pvParam, bool bIOFailure, SteamAPICall_t hSteamAPICall ) = 0;
	//         int GetICallback() { return m_iCallback; }
	//         virtual int GetCallbackSizeBytes() = 0;
	//     protected:
	//         enum { k_ECallbackFlagsRegistered = 0x01, k_ECallbackFlagsGameServer = 0x02 };
	//         uint8 m_nCallbackFlags;
	//         int m_iCallback;
	//         friend class CCallbackMgr;
	//     };
	//
	// Note GetICallback is NOT virtual, so it takes no vtable slot. There are exactly
	// three virtual slots. There is deliberately no virtual destructor.
	//
	// *** THE ONE THING IN THIS FILE MOST LIKELY TO GET SOMEONE KILLED ***
	//
	// Run is OVERLOADED. MSVC does not emit an overload group in declaration order, it
	// emits it in REVERSE declaration order. So the vtable is NOT
	// [Run(void*), Run(void*,bool,uint64), GetCallbackSizeBytes]. [S3] was asked directly,
	// by giving the two overloads distinguishable bodies and reading the mangled names out
	// of the real object file:
	//
	//     ??_7MyCb@@6B@ DD FLAT:??_R4MyCb@@6B@        ; MyCb::`vftable'
	//         DD FLAT:?Run@MyCb@@UAEXPAX_N_K@Z        ; slot 0
	//         DD FLAT:?Run@MyCb@@UAEXPAX@Z            ; slot 1
	//         DD FLAT:?GetCallbackSizeBytes@MyCb@@UAEHXZ ; slot 2
	//
	// Decoding the mangling: "PAX_N_K" is (void*, bool, unsigned __int64) and plain "PAX"
	// is (void*). So the REAL layout is
	//
	//     slot 0 : Run( void *pvParam, bool bIOFailure, SteamAPICall_t hSteamAPICall )  <- 3 args
	//     slot 1 : Run( void *pvParam )                                                <- 1 arg
	//     slot 2 : GetCallbackSizeBytes()
	//
	// The three-argument call-result form is FIRST and the one-argument plain-callback form
	// is SECOND. The ordinary callback we care about, P2PSessionRequest_t, is delivered
	// through slot 1, not slot 0.
	//
	// And the object layout, also from [S3]:
	//
	//     class CCallbackBase  size(12):
	//      0   | {vfptr}
	//      4   | m_nCallbackFlags
	//          | <alignment member> (size=3)
	//      8   | m_iCallback
	//
	// so vtable pointer at +0, uint8 m_nCallbackFlags at +4 with three bytes of padding,
	// int m_iCallback at +8, total 12 bytes. steam_api.h has no #pragma pack anywhere, so
	// this is default packing.
	//
	// THE SAFE WAY TO BUILD ONE, and the reason the struct below looks like it does: if you
	// declare the two overloads in the SDK's own declaration order, MSVC applies the same
	// reversal to your class that it applied to Valve's, so your vtable matches what
	// steam_api.dll expects. The reversal cancels out. So DECLARE THEM IN SDK ORDER AND DO
	// NOT "FIX" THE ORDER. The only situation where you must hand-write the reversed order
	// is if you build the vtable yourself as an explicit array of function pointers, in
	// which case the array literal has to be
	// { Run_threeArg, Run_oneArg, GetCallbackSizeBytes }.
	//
	// Two more things that are preconditions, not decoration:
	//   - m_nCallbackFlags and m_iCallback must be initialised before you register.
	//     SteamAPI_RegisterCallback sets k_ECallbackFlagsRegistered in m_nCallbackFlags
	//     itself, so start it at 0 and set m_iCallback to the k_iCallback you are
	//     registering for.
	//   - Callbacks are only dispatched from inside SteamAPI_RunCallbacks, which the GAME
	//     calls on its own thread. So Run fires on whatever thread the game pumps Steam
	//     from. Do not touch game state from in there without thinking about it, just
	//     record the event and handle it on our own tick.
	//   - Unregister before the object dies. A registered CCallbackBase that gets freed
	//     leaves steam_api.dll holding a dangling pointer it will call later.
	//
	// CONFIDENCE: the layout and the slot order above are verified, the first from Valve's
	// own header and the second from the real compiler. What is NOT verified by experiment
	// is that the shipped steam_api.dll dispatches through these slots as expected at
	// runtime, because that needs the game running. The layout is right. The behaviour is
	// consistent with the header it was built from, but it is an inference until someone
	// runs it.
	//
	// *** RECOMMENDED ALTERNATIVE: DO NOT USE CALLBACKS AT ALL ***
	//
	// For Al Bhed Workshop specifically, we do not need any of this. We already know every
	// peer's SteamID before the session starts, because that is how we set the session up.
	// The SDK header for AcceptP2PSessionWithUser states that calling SendP2PPacket to a
	// peer implicitly accepts that peer's pending session request, and that
	// AcceptP2PSessionWithUser may be called more than once for the same user harmlessly.
	// So have every peer proactively call AcceptP2PSessionWithUser on every other peer at
	// session start, and then just poll IsP2PPacketAvailable / ReadP2PPacket on our own
	// tick. That needs zero callback registration, no hand-rolled vtable, no lifetime
	// problem and no thread question, and it removes the single most fragile thing in this
	// header from our attack surface. With at most 3 players it costs 2 extra calls per
	// peer. Take this route. Use the struct below only if something later genuinely
	// requires a real callback.
	// ---------------------------------------------------------------------------

	// Flags from [S1] steam_api.h line 173.
	enum
	{
		k_ECallbackFlagsRegistered = 0x01,
		k_ECallbackFlagsGameServer = 0x02
	};

	// Worked, compilable, SDK-free CCallbackBase. Declaration order below is the SDK's
	// order on purpose. See the long comment above before changing anything here.
	//
	// Usage:
	//     workshop::SteamCallbackShim g_onSessionRequest;
	//     g_onSessionRequest.Init( workshop::P2PSessionRequest_t::k_iCallback,
	//                              sizeof( workshop::P2PSessionRequest_t ),
	//                              &MyHandler );
	//     SteamAPI_RegisterCallback( (void *)&g_onSessionRequest,
	//                                workshop::P2PSessionRequest_t::k_iCallback );
	//     ... later, before it is destroyed ...
	//     SteamAPI_UnregisterCallback( (void *)&g_onSessionRequest );
	class SteamCallbackShim
	{
	public:
		typedef void (*Handler)(void* pvParam);

		SteamCallbackShim()
		    : m_nCallbackFlags(0), m_iCallback(0), m_cbSize(0), m_pfnHandler(0)
		{
		}

		void Init(int iCallback, int cbCallbackSize, Handler pfn)
		{
			m_iCallback = iCallback;
			m_cbSize = cbCallbackSize;
			m_pfnHandler = pfn;
			// Leave m_nCallbackFlags alone. SteamAPI_RegisterCallback ORs in
			// k_ECallbackFlagsRegistered and SteamAPI_UnregisterCallback clears it.
		}

		bool IsRegistered() const
		{
			return (m_nCallbackFlags & k_ECallbackFlagsRegistered) != 0;
		}

		// Compile-time layout check. It lives as a member function because the two fields
		// it checks are protected, and because offsetof needs the class to be complete, so
		// the body is defined just below the class. Never called at runtime.
		static void AbiSelfCheck();

		// --- the three virtual slots, in SDK DECLARATION order. MSVC reverses the two
		// --- Run overloads for us, which is what makes this match the DLL. Do not reorder.

		// Ends up in vtable slot 1. This is the one ordinary callbacks arrive on.
		virtual void Run(void* pvParam)
		{
			if (m_pfnHandler)
				m_pfnHandler(pvParam);
		}

		// Ends up in vtable slot 0. This is the CallResult form, used by
		// SteamAPI_RegisterCallResult. We do not use call results, but the slot must exist
		// and must be safe to call, so forward the non-failure case and swallow the rest.
		virtual void Run(void* pvParam, bool bIOFailure, SteamAPICall_t hSteamAPICall)
		{
			(void)hSteamAPICall;
			if (!bIOFailure && m_pfnHandler)
				m_pfnHandler(pvParam);
		}

		// Ends up in vtable slot 2. Steam uses this to size the buffer it hands to Run, so
		// returning the wrong number here means Steam copies the wrong number of bytes.
		// It must be sizeof the callback struct you registered for, which is why Init takes
		// it rather than guessing. For P2PSessionRequest_t that is 8 and for
		// P2PSessionConnectFail_t it is 9.
		virtual int GetCallbackSizeBytes()
		{
			return m_cbSize;
		}

	protected:
		// Offsets +0 vfptr, +4 m_nCallbackFlags, +8 m_iCallback must match CCallbackBase
		// exactly, because steam_api.dll reads these two fields directly. The static_assert
		// block at the end of this file enforces it. Anything we add must come AFTER
		// m_iCallback.
		uint8 m_nCallbackFlags; // +4
		int m_iCallback;        // +8

		// Our own additions, past the end of the ABI-visible part.
		int m_cbSize;         // +12
		Handler m_pfnHandler; // +16
	};

	// The ABI-visible prefix of our shim has to line up with CCallbackBase: vfptr at +0,
	// m_nCallbackFlags at +4, m_iCallback at +8. steam_api.dll reads those two fields
	// directly, so if this ever drifts the DLL reads garbage.
	inline void SteamCallbackShim::AbiSelfCheck()
	{
		static_assert(offsetof(SteamCallbackShim, m_nCallbackFlags) == 4,
		    "m_nCallbackFlags must sit at +4 like CCallbackBase");
		static_assert(offsetof(SteamCallbackShim, m_iCallback) == 8,
		    "m_iCallback must sit at +8 like CCallbackBase");
	}

	// ---------------------------------------------------------------------------
	// steam_api.dll exports we rely on.
	//
	// Provenance: [S1] steamworks_sdk_131/steam_api.h for the declarations, plus
	// steamtypes.h line 13 for "#define S_CALLTYPE __cdecl" and steam_api.h line 41 for
	// "#define S_API extern "C"". So every one of these is extern "C" __cdecl, NOT
	// __stdcall. All of these names were confirmed present in the game's DLL export dump.
	//
	// Relevant declarations as they appear in [S1] steam_api.h:
	//     S_API ISteamNetworking *S_CALLTYPE SteamNetworking();            // line 119
	//     S_API ISteamClient     *S_CALLTYPE SteamClient();                // line 90
	//     S_API HSteamUser  GetHSteamUser();                               // line 378
	//     S_API HSteamPipe  GetHSteamPipe();                               // line 377
	//     S_API HSteamUser  SteamAPI_GetHSteamUser();                      // line 389
	//     S_API HSteamPipe  SteamAPI_GetHSteamPipe();                      // line 371
	//     S_API void S_CALLTYPE SteamAPI_RunCallbacks();                   // line 146
	//     S_API void S_CALLTYPE SteamAPI_RegisterCallback( class CCallbackBase *pCallback,
	//                                                      int iCallback ); // line 151
	//     S_API void S_CALLTYPE SteamAPI_UnregisterCallback( class CCallbackBase *pCallback ); // line 152
	//
	// IMPORTANT: SteamNetworking() returns the interface the GAME already initialised. The
	// game calls SteamAPI_Init itself, so we must NOT call SteamAPI_Init or
	// SteamAPI_Shutdown. We also should not call SteamAPI_RunCallbacks on our own schedule
	// if the game is already pumping it. Resolve these by name with GetProcAddress on the
	// already-loaded steam_api.dll rather than linking an import library.
	//
	// CCallbackBase * is spelled void * here so this block needs no SDK types. Pass the
	// address of a SteamCallbackShim.
	// ---------------------------------------------------------------------------

	typedef void*(__cdecl* FnSteamNetworking)();
	typedef void*(__cdecl* FnSteamClient)();
	// SteamUser and SteamFriends are direct exports of the shipped DLL too, same shape as
	// SteamNetworking: extern "C" __cdecl, no arguments, returning the already-initialised
	// interface. [S1] steam_api.h declares them as
	//     S_API ISteamUser    *S_CALLTYPE SteamUser();
	//     S_API ISteamFriends *S_CALLTYPE SteamFriends();
	// Cast the result to ISteamUser017 * / ISteamFriends014 *. Null-check both: they return
	// null if the game has not called SteamAPI_Init yet.
	typedef void*(__cdecl* FnSteamUser)();
	typedef void*(__cdecl* FnSteamFriends)();
	typedef HSteamUser(__cdecl* FnGetHSteamUser)();
	typedef HSteamPipe(__cdecl* FnGetHSteamPipe)();
	typedef void(__cdecl* FnSteamAPI_RunCallbacks)();
	typedef void(__cdecl* FnSteamAPI_RegisterCallback)(void* pCallback, int iCallback);
	typedef void(__cdecl* FnSteamAPI_UnregisterCallback)(void* pCallback);

