def _text(ea, name, core_lo, core_hi):
    mark = "" if core_lo <= ea <= core_hi else "?"
    return "TU: %s%s (TRANSLATION_UNITS.md)" % (name, mark)


def _plan():
    import idautils
    import idc
    plan, has_tu, has_other = [], 0, 0
    for start, end, name, core_lo, core_hi in ROWS:
        for ea in idautils.Functions(start, end + 1):
            old = (idc.get_func_cmt(ea, 1) or "") + (idc.get_func_cmt(ea, 0) or "")
            if old:
                if "(TRANSLATION_UNITS.md)" in old:
                    has_tu += 1
                else:
                    has_other += 1
                continue
            t = _text(ea, name, core_lo, core_hi)
            if len(t) > MAX_LINE:
                continue
            plan.append((ea, t))
    return plan, has_tu, has_other


def main(dry_run=DRY_RUN, verbose=VERBOSE):
    import idc
    plan, has_tu, has_other = _plan()
    for ea, t in plan:
        if verbose:
            print("cmt   0x%X %s" % (ea, t))
    sure = sum(1 for _, t in plan if "?" not in t)
    print("%d to comment (%d in a proved core, %d at an inferred edge), %d already carry a TU comment, "
          "%d skipped because they have another comment" % (len(plan), sure, len(plan) - sure, has_tu, has_other))
    if dry_run:
        print("DRY_RUN, nothing written")
        return len(plan)
    failed = 0
    for ea, t in plan:
        if not idc.set_func_cmt(ea, t, 1):
            print("FAILED 0x%X" % ea)
            failed += 1
    print("commented %d, failed %d. The database is NOT saved, save it when you are happy" % (len(plan) - failed, failed))
    return len(plan) - failed


def headless():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--idb", required=True, help="a COPY of the database")
    ap.add_argument("--apply", action="store_true", help="write the comments, the database is not saved")
    ap.add_argument("--rehearse", action="store_true", help="dry run, apply, dry run again, in one session")
    ap.add_argument("--verbose", action="store_true")
    a = ap.parse_args()
    import idapro
    if idapro.open_database(a.idb, run_auto_analysis=False) != 0:
        raise SystemExit("could not open %s" % a.idb)
    try:
        if a.rehearse:
            print("-- dry run")
            main(True, a.verbose)
            print("-- apply")
            main(False, a.verbose)
            print("-- second dry run")
            left = main(True, a.verbose)
            print("rehearsal %s" % ("clean, nothing left to add" if left == 0 else "NOT clean, %d left" % left))
        else:
            main(dry_run=not a.apply, verbose=a.verbose)
    finally:
        idapro.close_database(save=False)


if __name__ == "__main__":
    if "idaapi" in sys.modules or "ida_kernwin" in sys.modules:
        main()
    else:
        headless()
