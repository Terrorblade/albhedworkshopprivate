	// ---------------------------------------------------------------------------
	// EP2PSend
	//
	// Provenance: [S1] steamworks_sdk_131/isteamnetworking.h lines 33-56, verbatim
	// enumerator values. Corroborated by [S2] and by the SteamNetworking006 mirror.
	//
	// MAXIMUM PAYLOAD PER MODE. This is what the Valve header itself states, in its own
	// comments on each enumerator, and it is the answer to "can I go above 1200 bytes":
	//
	//   k_EP2PSendUnreliable            max 1200 bytes. The header says "Basic UDP send.
	//                                   Packets can't be bigger than 1200 bytes (your
	//                                   typical MTU size)." Can be lost, can arrive out
	//                                   of order. If NAT traversal is still in progress
	//                                   the packet is batched rather than dropped.
	//
	//   k_EP2PSendUnreliableNoDelay     max 1200 bytes, same as above, except that if the
	//                                   P2P connection is not established yet the packet
	//                                   is thrown away instead of batched. The header
	//                                   warns that using this for the first packet to a
	//                                   host "almost guarantees the packet will be
	//                                   dropped". Meant for voice. Do not use it for
	//                                   anything we care about.
	//
	//   k_EP2PSendReliable              up to 1 MB in a single message. YES, it fragments
	//                                   for you: the header says it "Does fragmentation/
	//                                   re-assembly of messages under the hood, as well as
	//                                   a sliding window for efficient sends of large
	//                                   chunks of data." So a reliable send above 1200
	//                                   bytes is legal and handled, it is not an error and
	//                                   you do not have to split it yourself.
	//
	//   k_EP2PSendReliableWithBuffering up to 1 MB as well, plus Nagle: sends accumulate
	//                                   until roughly one MTU (~1200 bytes) or about 200 ms
	//                                   have passed. Because the reliable stream is ordered
	//                                   you can queue several small buffered sends and then
	//                                   issue one plain k_EP2PSendReliable to flush them.
	//
	// So for Al Bhed Workshop: the 1200 byte cap you are holding yourself to is REQUIRED
	// for the two unreliable modes and is NOT required for the two reliable ones. Keep
	// capping the frequent unreliable traffic at 1200. Reliable control messages may
	// exceed it safely up to 1 MB, which is far more headroom than 3 players need.
	// ---------------------------------------------------------------------------

	enum EP2PSend
	{
		k_EP2PSendUnreliable = 0,
		k_EP2PSendUnreliableNoDelay = 1,
		k_EP2PSendReliable = 2, // the reliable one
		k_EP2PSendReliableWithBuffering = 3
	};

	// Payload ceilings, from the header comments quoted above. Named so call sites can
	// assert against them instead of hardcoding a number.
	enum
	{
		k_cbMaxP2PPacketUnreliable = 1200
	};
	enum
	{
		k_cbMaxP2PPacketReliable = 1024 * 1024
	};

