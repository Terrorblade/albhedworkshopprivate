	// ---------------------------------------------------------------------------
	// Self-checks. These cost nothing at runtime and they turn a silent ABI drift into a
	// compile error. Every number here was read out of the real compiler, see [S3].
	// ---------------------------------------------------------------------------

#define WORKSHOP_STEAM_ABI_CHECK(cond, msg) static_assert(cond, msg)

	WORKSHOP_STEAM_ABI_CHECK(sizeof(void*) == 4,
	    "SteamAbi.h is for 32-bit only");

	WORKSHOP_STEAM_ABI_CHECK(sizeof(SteamId) == 8,
	    "SteamId must be 8 bytes to stand in for CSteamID");

	WORKSHOP_STEAM_ABI_CHECK(sizeof(P2PSessionState_t) == 20,
	    "P2PSessionState_t must be 20 bytes");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionState_t, m_bConnectionActive) == 0, "");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionState_t, m_bConnecting) == 1, "");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionState_t, m_eP2PSessionError) == 2, "");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionState_t, m_bUsingRelay) == 3, "");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionState_t, m_nBytesQueuedForSend) == 4, "");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionState_t, m_nPacketsQueuedForSend) == 8, "");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionState_t, m_nRemoteIP) == 12, "");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionState_t, m_nRemotePort) == 16, "");

	// 8 and 9, not 8 and 16. See the callback block above for why the pack(1) on SteamId
	// is what makes this come out right.
	WORKSHOP_STEAM_ABI_CHECK(sizeof(P2PSessionRequest_t) == 8,
	    "P2PSessionRequest_t must be 8 bytes, GetCallbackSizeBytes depends on it");
	WORKSHOP_STEAM_ABI_CHECK(sizeof(P2PSessionConnectFail_t) == 9,
	    "P2PSessionConnectFail_t must be 9 bytes, not 12 and not 16");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionConnectFail_t, m_steamIDRemote) == 0, "");
	WORKSHOP_STEAM_ABI_CHECK(offsetof(P2PSessionConnectFail_t, m_eP2PSessionError) == 8, "");

	WORKSHOP_STEAM_ABI_CHECK((int)P2PSessionRequest_t::k_iCallback == 1202,
	    "P2PSessionRequest_t callback id must be 1202");
	WORKSHOP_STEAM_ABI_CHECK((int)P2PSessionConnectFail_t::k_iCallback == 1203,
	    "P2PSessionConnectFail_t callback id must be 1203");

	// The CCallbackBase prefix check lives in SteamCallbackShim::AbiSelfCheck above,
	// because the fields it checks are protected.

	WORKSHOP_STEAM_ABI_CHECK((int)k_EP2PSendReliable == 2,
	    "k_EP2PSendReliable must be 2");

	WORKSHOP_STEAM_ABI_CHECK((int)k_EFriendFlagImmediate == 0x04,
	    "k_EFriendFlagImmediate must be 0x04, it is what a friend picker passes");

	// The return-value interfaces are 4 bytes, just a vtable pointer, like every other
	// Steam interface. If one of these ever came out larger it would mean a stray data
	// member crept into the declaration and every slot index below it would be suspect.
	WORKSHOP_STEAM_ABI_CHECK(sizeof(ISteamUser017) == 4,
	    "ISteamUser017 must be just a vtable pointer");
	WORKSHOP_STEAM_ABI_CHECK(sizeof(ISteamFriends014) == 4,
	    "ISteamFriends014 must be just a vtable pointer");
	WORKSHOP_STEAM_ABI_CHECK(sizeof(ISteamNetworking005) == 4,
	    "ISteamNetworking005 must be just a vtable pointer");

	// GetSteamID and GetFriendByIndex return this by value through a hidden buffer. The
	// convention was verified for an 8-byte type specifically, so if SteamId ever changed
	// size the verification would no longer apply. Belt and braces with the size check
	// further up.
	WORKSHOP_STEAM_ABI_CHECK(sizeof(SteamId) == 8,
	    "SteamId must stay 8 bytes or the verified return convention no longer applies");

