	// ---------------------------------------------------------------------------
	// P2PSessionState_t, the struct GetP2PSessionState fills in.
	//
	// Provenance: [S1] isteamnetworking.h lines 68-78 for field order and types. The
	// struct sits inside a packing block that is pack(4) when VALVE_CALLBACK_PACK_SMALL
	// and pack(8) when VALVE_CALLBACK_PACK_LARGE. Which one applies is decided in
	// [S1] isteamclient.h lines 24-33:
	//
	//     #if defined(__linux__) || defined(__APPLE__)
	//     #define VALVE_CALLBACK_PACK_SMALL
	//     #else
	//     #define VALVE_CALLBACK_PACK_LARGE
	//     #endif
	//
	// We are Windows, so it is VALVE_CALLBACK_PACK_LARGE, that is #pragma pack(8).
	// Since no member here needs more than 4-byte alignment, pack(8) changes nothing and
	// the layout is the natural one.
	//
	// [S3] confirms with the real compiler, offsets and total size:
	//
	//     class P2PSessionState_t  size(20):
	//      0   | m_bConnectionActive
	//      1   | m_bConnecting
	//      2   | m_eP2PSessionError
	//      3   | m_bUsingRelay
	//      4   | m_nBytesQueuedForSend
	//      8   | m_nPacketsQueuedForSend
	//     12   | m_nRemoteIP
	//     16   | m_nRemotePort
	//          | <alignment member> (size=2)
	//
	// Total size 20 bytes, with 2 bytes of tail padding after m_nRemotePort. Zero it
	// before the call if you plan to read fields after a false return.
	// ---------------------------------------------------------------------------

#pragma pack(push, 8)

	struct P2PSessionState_t
	{
		uint8 m_bConnectionActive;     // +0  nonzero once the connection is open
		uint8 m_bConnecting;           // +1  nonzero while still trying
		uint8 m_eP2PSessionError;      // +2  EP2PSessionError, last error seen
		uint8 m_bUsingRelay;           // +3  nonzero if routed via a Steam relay (TURN)
		int32 m_nBytesQueuedForSend;   // +4
		int32 m_nPacketsQueuedForSend; // +8
		uint32 m_nRemoteIP;            // +12 may be a relay address, not the peer
		uint16 m_nRemotePort;          // +16
		                               // +18 two bytes tail padding, size is 20
	};

#pragma pack(pop)

	// ---------------------------------------------------------------------------
	// Callback ids and callback structs.
	//
	// Provenance for the base: [S1] steamworks_sdk_131/isteamclient.h declares the bases
	// as a run of single-enumerator enums. The networking one is
	//
	//     enum { k_iSteamNetworkingCallbacks = 1200 };
	//
	// so the Networking callback base is 1200. For context, neighbours are
	// k_iSteamUserCallbacks = 100, k_iSteamFriendsCallbacks = 300,
	// k_iSteamMatchmakingCallbacks = 500, k_iSteamUtilsCallbacks = 700,
	// k_iSteamUserStatsCallbacks = 1100, k_iClientRemoteStorageCallbacks = 1300.
	//
	// Provenance for the structs and their offsets: [S1] isteamnetworking.h lines 275-302,
	// inside the same pack(8) block as P2PSessionState_t. Confirmed by [S3]:
	//
	//     class P2PSessionRequest_t      size(8):
	//      0   | CSteamID m_steamIDRemote
	//
	//     class P2PSessionConnectFail_t  size(9):
	//      0   | CSteamID m_steamIDRemote
	//      8   | m_eP2PSessionError
	//
	// P2PSessionConnectFail_t really is 9 bytes, not 12. That is not a mistake. CSteamID
	// was declared under pack(1) at its own definition, so its alignment requirement is 1,
	// and an enclosing pack(8) can only ever lower alignment, never raise it. So the
	// uint8 lands at +8 and there is no tail padding. If you declare these structs with a
	// plain uint64 in place of CSteamID instead of a pack(1) type, the uint64's 8-byte
	// alignment makes the struct 16 bytes and GetCallbackSizeBytes starts lying to Steam.
	// That is why SteamId above is pack(1). The static_asserts at the bottom of this file
	// will fail loudly if that ever drifts.
	// ---------------------------------------------------------------------------

	enum
	{
		k_iSteamNetworkingCallbacks = 1200
	};

#pragma pack(push, 8)

	// Posted when a peer sends us a packet and we have no session with them yet. Respond
	// with AcceptP2PSessionWithUser if you want to talk to them. If you ignore it and the
