	// ---------------------------------------------------------------------------
	// RETURNING A CSteamID BY VALUE - read this before touching GetSteamID or
	// GetFriendByIndex.
	//
	// An 8-byte class or struct return value on 32-bit MSVC is NOT returned in the
	// EAX:EDX register pair. It is returned through a hidden return-buffer pointer: the
	// CALLER allocates an 8-byte temporary, passes its address as an extra invisible
	// argument pushed on the stack, and the callee fills that buffer in and returns the
	// same pointer back in EAX.
	//
	// A raw uint64 return, by contrast, DOES come back in EAX:EDX with no buffer at all.
	// These are two completely different conventions. So declaring GetSteamID as returning
	// uint64 is NOT a harmless simplification the way it was for CSteamID *parameters* - it
	// is wrong, it leaves the stack unbalanced and it reads the result from the wrong place.
	// This is the one asymmetry in this header: for arguments, uint64 and CSteamID are
	// interchangeable, and for RETURN VALUES they are not.
	//
	// [S3] was asked directly. Three variants were compiled, all 8 bytes:
	//   (A) CSteamID as the SDK declares it, pack(1), with user-declared constructors
	//   (B) a trivial pack(1) POD struct holding one uint64, no constructors
	//   (C) a plain uint64
	//
	// (A) and (B) produced BYTE-IDENTICAL code, so whether the type has constructors makes
	// no difference at this size. (C) was completely different. For (A) and (B):
	//
	//     mov  ecx, DWORD PTR _p$[esp-4]   ; this -> ECX
	//     lea  edx, DWORD PTR $T1[esp]     ; address of the caller's 8-byte temporary
	//     sub  esp, 8                      ; reserve that temporary
	//     mov  eax, DWORD PTR [ecx]        ; vtable
	//     push edx                         ; HIDDEN return-buffer pointer
	//     call DWORD PTR [eax]             ; slot 0
	//     mov  edx, eax                    ; callee handed the buffer pointer back in EAX
	//     mov  eax, DWORD PTR [edx]        ; low dword
	//     mov  edx, DWORD PTR [edx+4]      ; high dword
	//     add  esp, 8
	//     ret  0                           ; callee popped the hidden pointer
	//
	// whereas (C), the uint64 version, was just:
	//
	//     mov  ecx, DWORD PTR _p$[esp-4]
	//     mov  eax, DWORD PTR [ecx]
	//     mov  eax, DWORD PTR [eax]
	//     jmp  eax                         ; tail call, result already in EAX:EDX
	//
	// WHAT THIS MEANS FOR HOW YOU DECLARE IT. Because variant (B) - a trivial pack(1) POD
	// holding a uint64, which is exactly our SteamId type - generates identical code to the
	// real CSteamID, declaring these methods as returning SteamId is correct. That is what
	// the two interfaces below do, and then MSVC sets up the hidden buffer for you and you
	// never have to think about it again. Just call it and use the result.
	//
	// If you ever hand-roll a thunk for one of these, the hidden pointer has to be spelled
	// out explicitly as the first parameter after self, and the return type is the pointer:
	//
	//     typedef SteamId *(__thiscall *FnGetSteamID)( void *self, SteamId *pRetBuf );
	//
	// Where the method also takes real arguments, the hidden buffer pointer comes FIRST,
	// before them, in the argument list. [S3] confirmed the ordering on GetFriendByIndex,
	// see the note in the ISteamFriends014 block below.
	// ---------------------------------------------------------------------------

