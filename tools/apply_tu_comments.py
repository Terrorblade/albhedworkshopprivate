"""
Add the translation unit of each function from reversing/TRANSLATION_UNITS.md to the FFX.exe IDB
as a short repeatable function comment.

Only the rows that name a source file are applied: the files a __FILE__ path string names (the
string is read by a function in the row) and the files other docs proved (RCBG.md, RCDATA.md,
RCFLEX.md). The unnamed unit_<addr> rows are not applied, because their edges move when the rules
in tools/tu_map.py change and a comment in the IDB should not.

Each row carries its proved core. Inside the core the comment is

    TU: chr.c (TRANSLATION_UNITS.md)

and outside it, where the edge of the file is only inferred, it is

    TU: chr.c? (TRANSLATION_UNITS.md)

A function gets a comment only when it has no function comment at all, repeatable or not. So
running the script twice is harmless and an existing comment is never touched. Every comment is
far below the 1000 characters per line IDA allows.

ROWS was generated by tools/tu_map.py report --tsv (columns 1, 2, 4, 7 and 8 of the file rows).
Regenerate it from there rather than editing it by hand.

DRY_RUN is True by default. A dry run prints what it would add and changes nothing. The script
never saves the database, save it yourself.

Run it inside IDA (File > Script file), or headless through idalib on a COPY of the database:

    python apply_tu_comments.py --idb path/to/copy/FFX.exe.i64 [--apply] [--rehearse] [--verbose]

--rehearse runs a dry run, applies, and runs a second dry run in one session, which should then
find nothing to add. Headless runs close the database without saving.
"""

