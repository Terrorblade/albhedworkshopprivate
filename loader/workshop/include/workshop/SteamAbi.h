	// ---------------------------------------------------------------------------
	// CSteamID
	//
	// Provenance: [S1] steamworks_sdk_131/steamclientpublic.h, class CSteamID at line
	// 402, sitting inside a "#pragma pack( push, 1 )" that opens at line 397. The real
	// SDK class is a union of a bitfield struct and a uint64:
	//
	//     union SteamID_t {
	//         struct SteamIDComponent_t {
	//             uint32       m_unAccountID       : 32;   // bits  0..31
	//             unsigned int m_unAccountInstance : 20;   // bits 32..51
	//             unsigned int m_EAccountType      :  4;   // bits 52..55
	//             EUniverse    m_EUniverse         :  8;   // bits 56..63
	//         } m_comp;
	//         uint64 m_unAll64Bits;
	//     } m_steamid;
	//
	// It declares no virtual functions, so there is no vptr and the object is exactly
	// its 8 payload bytes. [S3] confirms with the real compiler:
	//
	//     class CSteamID  size(8):
	//      0   | SteamID_t m_steamid
	//
	// HOW IT IS PASSED BY VALUE, which is the detail that silently misaligns argument
	// lists if you get it wrong. On MSVC x86 a class passed by value is copied onto the
	// stack, it is never passed in a register and it is never silently turned into a
	// hidden pointer, regardless of whether it has constructors. So a by-value CSteamID
	// occupies exactly 8 bytes of the argument area, low dword at the lower address,
	// which is identical to passing a uint64 by value. [S3] proves it. Compiling
	//
	//     p->SendP2PPacket( CSteamID( rawSteamId ), data, len, k_EP2PSendReliable, 0 );
	//
	// gave this, with rawSteamId declared as a plain uint64:
	//
	//     mov  ecx, DWORD PTR _p$[esp-4]        ; this -> ECX
	//     push 0                                ; nChannel        (pushed first = last arg)
	//     push 2                                ; eP2PSendType
	//     push DWORD PTR _len$[esp+4]           ; cubData
	//     mov  eax, DWORD PTR [ecx]             ; load vtable
	//     push DWORD PTR _data$[esp+8]          ; pubData
	//     push DWORD PTR _rawSteamId$[esp+16]   ; CSteamID high dword
	//     mov  eax, DWORD PTR [eax]             ; vtable[0] = SendP2PPacket
	//     push DWORD PTR _rawSteamId$[esp+16]   ; CSteamID low dword (esp moved by 4)
	//     call eax
	//     ret  0                                ; caller does NOT clean up -> callee pops
	//
	// Two pushes of the same uint64, high dword then low dword, and no stack fixup after
	// the call. That is a little-endian 8-byte value in the argument area and a
	// callee-pops convention, exactly as a uint64 argument to a __thiscall method.
	//
	// CONSEQUENCE, and this is the practical rule for this codebase: everywhere a Steam
	// method takes a CSteamID by value, we declare the parameter as uint64 instead. It is
	// byte-for-byte the same and it removes a whole category of mistake. Where a method
	// takes CSteamID*, we use SteamId* so the 8 bytes are still named.
	// ---------------------------------------------------------------------------

#pragma pack(push, 1)

	// Plain 8-byte stand-in for CSteamID. POD, no constructors, no vtable, alignment 1,
	// so it can sit inside the callback structs at the same offsets the SDK gives them.
	struct SteamId
	{
		uint64 m_unAll64Bits;
	};

#pragma pack(pop)

	// Build one from a raw uint64. A SteamID you got from the Steam API, from a lobby
	// member list, or out of a config file is already in this form, so this is just a
	// cast with a name on it.
	inline SteamId MakeSteamId(uint64 raw)
	{
		SteamId id;
		id.m_unAll64Bits = raw;
		return id;
	}

	inline uint64 SteamIdToUint64(const SteamId& id)
	{
		return id.m_unAll64Bits;
	}

	// Field accessors, in case you ever need to sanity check that a SteamID really is an
	// individual account on the public universe before trusting it.
	// Bit positions from the bitfield widths in [S1] steamclientpublic.h quoted above.
	inline uint32 SteamIdAccountId(uint64 raw)
	{
		return (uint32)(raw & 0xFFFFFFFFull);
	}
	inline uint32 SteamIdAccountInstance(uint64 raw)
	{
		return (uint32)((raw >> 32) & 0xFFFFFull);
	}
	inline uint32 SteamIdAccountType(uint64 raw)
	{
		return (uint32)((raw >> 52) & 0xFull);
	}
	inline uint32 SteamIdUniverse(uint64 raw)
	{
		return (uint32)((raw >> 56) & 0xFFull);
	}

