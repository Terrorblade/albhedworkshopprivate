// SteamAbi.h - hand-declared binary layout for the subset of the Steamworks API
// that Al Bhed Workshop calls inside the FFX HD process.
//
// WHY THIS FILE EXISTS
// The game ships steam_api.dll at
//   G:\Steam\steamapps\common\FINAL FANTASY FFX&FFX-2 HD Remaster\steam_api.dll
// (32-bit, 86 exports, file version 02.37.91.26). That DLL exports no flat API, so
// there is no SteamAPI_ISteamNetworking_SendP2PPacket to call. Every interface call
// has to go through a C++ vtable. There is no Steamworks SDK on this machine and the
// mod does not link one. So we declare the layout ourselves, here, once.
//
// Getting a slot index wrong here means calling an arbitrary function with the wrong
// arguments inside the game process. Do not edit this file from memory. Every fact
// below carries a provenance comment naming the source it came from. If you need to
// add something, go verify it the same way and write down where you got it.
//
// HOW THE FACTS BELOW WERE ESTABLISHED
//
//  [S1] Valve's own SDK headers, version-pinned, from Valve's Proton repository:
//       https://raw.githubusercontent.com/ValveSoftware/Proton/proton_8.0/
//         lsteamclient/steamworks_sdk_131/isteamnetworking.h
//       (also isteamclient.h, steamclientpublic.h, steam_api.h, steamtypes.h from the
//       same steamworks_sdk_131 directory). This is Valve shipping Valve's own SDK, so
//       it is a primary source, not a mirror.
//
//       We pinned 1.31 because that is the SDK whose STEAMCLIENT_INTERFACE_VERSION is
//       "SteamClient016", which is the string present in the game's steam_api.dll. We
//       swept steamworks_sdk_125 through _142 and confirmed:
//         SDK 1.25 - 1.28 -> SteamClient012
//         SDK 1.29        -> SteamClient014
//         SDK 1.30        -> SteamClient015
//         SDK 1.31        -> SteamClient016   <-- matches the shipped DLL
//         SDK 1.32 - 1.42 -> SteamClient017
//       So the DLL is SDK 1.31, slightly older than the 1.34-1.37 we first guessed.
//       It does not matter for networking: isteamnetworking.h is byte-for-byte
//       IDENTICAL (md5 300006747a99ccf176155b1333f6a87f) across every one of
//       steamworks_sdk_125 through _142, and every one of them says
//       STEAMNETWORKING_INTERFACE_VERSION "SteamNetworking005". The interface simply
//       did not change over that whole span, so the layout below is not sensitive to
//       which of those SDKs the DLL was actually built from.
//
//  [S2] SteamRE/open-steamworks, which is reverse engineered from the real shipping
//       steamclient.dll rather than copied from a header:
//       https://raw.githubusercontent.com/SteamRE/open-steamworks/master/
//         Open%20Steamworks/ISteamNetworking005.h   (and ISteamClient016.h)
//       Independent of [S1] and it agrees on method order and signatures.
//
//  [S3] The actual MSVC x86 compiler on this machine, 19.29.30159 for x86, asked to
//       dump the layout it really produces with -d1reportSingleClassLayout and to emit
//       the real call sequence with -FAs. This is the compiler that builds this mod, so
//       it is the final authority on vtable order, struct offsets and argument passing.
//       Transcripts of those runs are quoted inline below.
//
//  Cross-check that caught nothing but is worth recording: an independent mirror of a
//  NEWER SDK (SteamNetworking006, julianxhokaxhiu/SteamworksSDKCI) lists the same 22
//  methods in the same order. 006 differs from 005 only by swapping uint32 nIP for
//  SteamIPAddress_t in the four legacy socket methods. The P2P half, slots 0 to 7, is
//  unchanged between 005 and 006.
//
// CALLING CONVENTION, IN ONE PARAGRAPH
// These are MSVC C++ virtual methods on 32-bit Windows, so they are __thiscall: the
// interface pointer goes in ECX, the declared arguments are pushed on the stack right
// to left, and the CALLEE pops them. Verified from real codegen in [S3], see the
// disassembly quoted above ISteamNetworking005 below. The easy and safe way to call
// them is to declare the abstract class in this file and let MSVC do it, which is what
// ISteamNetworking005 below is for. Raw __thiscall function pointer typedefs are also
// provided for the cases where you want to bypass the class, and they were verified to
// produce byte-identical code to the virtual call.
//
// Style note: this header is deliberately plain C++ with no SDK and no STL. The only
// include is <stddef.h>, for offsetof, so the static_asserts at the bottom can check
// that whatever compiler you are using actually agrees with the offsets written here.

